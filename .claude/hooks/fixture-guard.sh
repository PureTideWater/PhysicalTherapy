#!/usr/bin/env bash
# PreToolUse on Edit|Write|MultiEdit. Refuses any X12 content under fixtures/ or packages/synth/ whose ISA06
# sender is not SYNTHSENDER, and any file anywhere that looks like a real remittance. Under fixtures/ or
# packages/synth/ it also refuses any write of a spreadsheet (.xlsx, .xls, .xlsm, .ods and the like), and checks
# the file a Write, Edit or MultiEdit would leave (a CSV or TSV above all) with the writer's own guard,
# packages/synth/src/guard/cli.ts: SYNTHSENDER in an identifier column of every data row (docs/adr/0059).
# Fails closed without jq, node or tsx.
set -u
command -v jq >/dev/null 2>&1 || { echo "fixture-guard: jq is required" >&2; exit 2; }
input=$(cat)
file_path=$(printf '%s' "$input" | jq -r '.tool_input.file_path // empty') || { echo "fixture-guard: the hook input is not JSON" >&2; exit 2; }
content=$(printf '%s' "$input" | jq -r '.tool_input.content // .tool_input.new_string // empty')
if [ -n "$content" ]; then
  case "$content" in
    ISA*)
      sender=$(printf '%s' "$content" | cut -c36-50 | tr -d ' ')
      if [ "$sender" != "SYNTHSENDER" ]; then
        echo "Blocked: $file_path contains an X12 interchange whose sender is not SYNTHSENDER. Real remittances never enter the repository. Generate a twin with pnpm synth." >&2
        exit 2
      fi ;;
  esac
fi

# The file's path in its own repository (a worktree is its own): "." and ".." segments taken out, symbolic links
# in the part that exists resolved, and compared in any case, so no spelling of a fixture's path slips past.
[ -n "$file_path" ] || exit 0
cwd=$(printf '%s' "$input" | jq -r '.cwd // empty')
root=$(cd "${cwd:-.}" 2>/dev/null && git rev-parse --show-toplevel 2>/dev/null) || root="${cwd:-$PWD}"
case "$file_path" in /*) abs="$file_path" ;; *) abs="$root/$file_path" ;; esac
parts=()
clean=()
IFS=/ read -r -a parts <<< "$abs"
for part in ${parts[@]+"${parts[@]}"}; do
  case "$part" in
    ''|.) ;;
    ..) [ "${#clean[@]}" -eq 0 ] || unset 'clean[${#clean[@]}-1]' ;;
    *) clean+=("$part") ;;
  esac
done
abs=$(printf '/%s' ${clean[@]+"${clean[@]}"})
dir=$(dirname "$abs")
while [ ! -d "$dir" ]; do dir=$(dirname "$dir"); done
real=$(cd "$dir" 2>/dev/null && pwd -P) || real="$dir"
tail=${abs#"$dir"}
abs="${real%/}/${tail#/}"
own=$(cd "$real" 2>/dev/null && git rev-parse --show-toplevel 2>/dev/null) || own="$root"
rel=${abs#"$own"/}
lower=$(printf '%s' "$rel" | tr '[:upper:]' '[:lower:]')
case "$lower" in fixtures/*|packages/synth/*) ;; *) exit 0 ;; esac
case "$lower" in
  *.xlsx|*.xls|*.xlsm|*.xlsb|*.xltx|*.xltm|*.ods|*.fods|*.numbers)
    echo "Blocked: $file_path is a spreadsheet under fixtures/ or packages/synth/. A workbook fixture is generated by packages/synth, which checks it for SYNTHSENDER; it is never written by hand." >&2
    exit 2 ;;
  # Source, data and documents: no fixture rule reads them, and the hook stays fast for them.
  *.ts|*.tsx|*.js|*.mjs|*.cjs|*.json|*.md) exit 0 ;;
esac

# Anything else there (a CSV or TSV, an .835, a text file) is checked as the file the call would leave.
here=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
tsx="$here/node_modules/.bin/tsx"
command -v node >/dev/null 2>&1 || { echo "fixture-guard: node is required to check $file_path" >&2; exit 2; }
[ -x "$tsx" ] || { echo "fixture-guard: tsx is required to check $file_path (pnpm install)" >&2; exit 2; }
printf '%s' "$input" | "$tsx" "$here/packages/synth/src/guard/cli.ts" --hook --label "$rel" --file "$abs" && exit 0
exit 2
