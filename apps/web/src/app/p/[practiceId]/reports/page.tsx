import { randomUUID } from 'node:crypto';

import { Badge, Card, CardContent, CardDescription, CardHeader, CardTitle, EmptyState, Input, Label, PermissionState } from '@tp/ui';
import type { Metadata } from 'next';
import Link from 'next/link';

import { ActionForm } from '../../../../components/action-form';
import { roleNames, utc } from '../../../../components/format';
import { ReleaseState, ReportStatusBadge } from '../../../../components/reports/display';
import { DocumentStatusBadge } from '../../../../components/reports/documents';
import { Money, Pager } from '../../../../components/remittances/display';
import { ShareLink } from '../../../../components/share';
import { AppShell, Forbidden } from '../../../../components/shell';
import { loadPage } from '../../../../lib/http/next';
import type { ExportRecord } from '../../../../lib/reports/documents';
import { reportsPage } from '../../../../lib/routes/reports';
import { generateReportFormAction } from './actions';
import { generateReportDocumentFormAction } from './documents/actions';

export const metadata: Metadata = { title: 'Reports' };

type Props = { readonly params: Promise<{ practiceId: string }>; readonly searchParams: Promise<Record<string, string | string[] | undefined>> };

const KIND_WORDS: Readonly<Record<ExportRecord['kind'], string>> = {
  audit_report: 'audit report',
  roi_statement: 'ROI statement',
  report_document: 'report',
  monthly_summary: 'monthly summary',
  packet_export: 'packet',
};

const FILE_WORDS: Readonly<Record<ExportRecord['file'], string>> = {
  pdf: 'PDF',
  csv: 'CSV',
  line_csv: 'line CSV',
  packet: 'PDF or CSV schedule, identifiers inserted',
};

/** Where an export history entry's record is. */
function exportHref(practiceId: string, entry: ExportRecord): string | null {
  if (entry.objectId === null) {
    return entry.kind === 'monthly_summary' ? `/p/${practiceId}/reports/monthly` : null;
  }
  switch (entry.kind) {
    case 'audit_report':
      return `/p/${practiceId}/reports/${entry.objectId}`;
    case 'roi_statement':
      return `/p/${practiceId}/reports/roi/${entry.objectId}`;
    case 'report_document':
      return `/p/${practiceId}/reports/documents/${entry.objectId}`;
    case 'packet_export':
      return entry.caseId === null ? null : `/p/${practiceId}/cases/${entry.caseId}/packet?version=${entry.objectId}`;
    case 'monthly_summary':
      return `/p/${practiceId}/reports/monthly`;
  }
}

/**
 * The Reports screen (PRD 7, Reports: "Audit report, monthly summary, ROI statement, coverage report;
 * export history ... Generate, download, share within the organization ... Every total links to its
 * stage; line-level export logged"; PRD 5, J12; PRD 6, Reports and exports: "a viewer cannot export
 * line-level PHI"). Audit reports are generated by the worker from a pricing run in effect after its
 * triage and released once a reimbursement reviewer signs; the monthly summary and the coverage report
 * are generated with their figures as they stand and printed by the worker; ROI statements come from
 * the recovery ledger. Line-level exports (an audit report's line CSV, a packet's export) are for the
 * roles that export PHI, and every download of every report file is listed here.
 */
export default async function ReportsPage(props: Props) {
  const page = await loadPage(reportsPage, props);
  if (page.kind === 'forbidden') {
    return <Forbidden shell={page.shell} section="reports" roles={page.roles} message={page.message} nextStep="Ask the practice's administrator for access." />;
  }
  const { practiceId, reports, documents, history, runs, canGenerate, canExport, canReview, lastMonth, origin, roles } = page.data;
  const path = `/p/${practiceId}/reports`;
  const pageQuery = { page: String(reports.page), documents: String(documents.page), history: String(history.page) };
  return (
    <AppShell shell={page.shell} section="reports">
      <div className="flex flex-col gap-1">
        <h1 className="text-2xl font-semibold tracking-tight">Reports</h1>
        <p className="text-sm text-muted-foreground">
          Every report keeps its stages apart: actionable, payer approved and recovered are three numbers, never one, with flagged and validated below them; recovered is only ever the recovery ledger’s posted or deposited cash. Every
          total links to the stage it came from.
        </p>
      </div>
      {canExport ? null : (
        <PermissionState
          role={roleNames(roles)}
          cannot="export line-level PHI (an audit report’s line CSV, a packet’s export)"
          nextStep="Every report’s PDF and its summary CSV are yours to download; a billing manager or the firm’s principal exports lines, and each such export is logged below."
        />
      )}
      <section aria-label="Audit reports" className="flex flex-col gap-3">
        <h2 className="text-lg font-semibold">Audit reports</h2>
        <p className="text-sm text-muted-foreground">
          Coverage, anomalies (investigatory), validated discrepancies and actionable amounts kept apart, with the pursuit cost and the evidence gaps. A report is released only after a reimbursement reviewer signs its attestation.
        </p>
        {canGenerate ? (
          <Card role="region" aria-label="Generate an audit report">
            <CardHeader>
              <CardTitle>Generate an audit report</CardTitle>
              <CardDescription>The report job triages the run on today’s date, then prints the report to PDF and writes the line CSV; the numbers never change once generated.</CardDescription>
            </CardHeader>
            <CardContent>
              {runs.length === 0 ? (
                <p className="text-sm text-muted-foreground">No pricing run in effect yet: a complete run, or a re-run once it is accepted.</p>
              ) : (
                <ActionForm action={generateReportFormAction} submit="Generate the report" className="flex max-w-xl flex-col gap-3">
                  <input type="hidden" name="requestKey" value={randomUUID()} />
                  <input type="hidden" name="practiceId" value={practiceId} />
                  <div className="flex flex-col gap-1.5">
                    <Label htmlFor="report-run">Pricing run</Label>
                    <select id="report-run" name="runId" className="h-9 rounded-md border bg-background px-2 text-sm" required>
                      {runs.map((run) => (
                        <option key={run.id} value={run.id}>
                          {run.periodFrom} to {run.periodTo} (release {run.releaseNo})
                        </option>
                      ))}
                    </select>
                  </div>
                </ActionForm>
              )}
            </CardContent>
          </Card>
        ) : null}
        {reports.total === 0 ? (
          <EmptyState title="No audit report yet" nextStep="A billing manager or analyst generates one from the pricing run in effect for its period." />
        ) : (
          <ul className="flex flex-col gap-3" aria-label="Reports">
            {reports.items.map((report) => {
              const base = `${path}/${report.id}`;
              return (
                <li key={report.id} className="rounded-md border p-4" data-report={report.id} data-status={report.status}>
                  <div className="flex flex-wrap items-center gap-2">
                    <Link className="font-medium underline" href={base}>
                      Service {report.periodFrom} to {report.periodTo}
                    </Link>
                    <ReportStatusBadge status={report.status} />
                    <ReleaseState report={report} />
                    <span className="text-xs text-muted-foreground">
                      Requested {utc(report.createdAt)} by {report.requestedBy ?? 'a member of the practice'}
                      {report.generatedAt === null ? '' : `; generated ${utc(report.generatedAt)}, windows judged on ${report.asOf ?? '—'}`}
                    </span>
                  </div>
                  {report.headline === null ? null : (
                    <p className="pt-2 text-sm" data-headline={report.id}>
                      <Link className="underline" href={`${base}#stage-actionable`}>
                        {report.headline.labels.actionable}
                      </Link>{' '}
                      <Money value={report.headline.actionable_cents} />;{' '}
                      <Link className="underline" href={`${base}#stage-payer-approved`}>
                        {report.headline.labels.payer_approved}
                      </Link>{' '}
                      <Money value={report.headline.payer_approved_cents} />;{' '}
                      <Link className="underline" href={`${base}#stage-recovered`}>
                        {report.headline.labels.recovered}
                      </Link>{' '}
                      <Money value={report.headline.recovered_cents} />. Below them:{' '}
                      <Link className="underline" href={`${base}#stage-flagged`}>
                        {report.headline.labels.flagged}
                      </Link>{' '}
                      {report.headline.flagged_lines} lines;{' '}
                      <Link className="underline" href={`${base}#stage-validated`}>
                        {report.headline.labels.validated}
                      </Link>{' '}
                      <Money value={report.headline.validated_cents} />.
                    </p>
                  )}
                  {report.status !== 'ready' ? null : (
                    <p className="flex flex-wrap gap-3 pt-2 text-sm">
                      <a className="underline" href={`${base}/pdf`}>
                        Download the PDF
                      </a>
                      {canExport ? (
                        <a className="underline" href={`${base}/csv`}>
                          Download the line CSV
                        </a>
                      ) : (
                        <span className="text-muted-foreground">Line CSV: line-level PHI, for the roles that export it</span>
                      )}
                      {canReview && report.attestedAt === null ? (
                        <Link className="underline" href={`${base}/review`}>
                          Open the reviewer checklist
                        </Link>
                      ) : null}
                    </p>
                  )}
                </li>
              );
            })}
          </ul>
        )}
        <Pager path={path} query={{ documents: pageQuery.documents, history: pageQuery.history }} page={reports.page} pages={reports.pages} total={reports.total} noun="Reports" />
      </section>
      <div className="grid gap-4 lg:grid-cols-3">
        <Card role="region" aria-label="Monthly variance summary">
          <CardHeader>
            <CardTitle>Monthly variance summary</CardTitle>
            <CardDescription>A month’s lines by stage and payer, counts and totals, never one stage added to another; with the monthly digests.</CardDescription>
          </CardHeader>
          <CardContent className="flex flex-col gap-3">
            <Link className="text-sm underline" href={`${path}/monthly`}>
              Open the monthly summary
            </Link>
            {canGenerate ? (
              <ActionForm action={generateReportDocumentFormAction} submit="Generate the month’s PDF" variant="outline" className="flex flex-col gap-2">
                <input type="hidden" name="requestKey" value={randomUUID()} />
                <input type="hidden" name="practiceId" value={practiceId} />
                <input type="hidden" name="kind" value="monthly_summary" />
                <div className="flex flex-col gap-1.5">
                  <Label htmlFor="document-month">Month of service</Label>
                  <Input id="document-month" name="month" type="month" defaultValue={lastMonth} required className="w-44" />
                </div>
              </ActionForm>
            ) : null}
          </CardContent>
        </Card>
        <Card role="region" aria-label="ROI statements">
          <CardHeader>
            <CardTitle>ROI statements</CardTitle>
            <CardDescription>Recovered cash net of recoupments against the fees paid, quarterly and on demand, every figure with the ledger entries it sums.</CardDescription>
          </CardHeader>
          <CardContent>
            <Link className="text-sm underline" href={`${path}/roi`}>
              Open the ROI statements
            </Link>
          </CardContent>
        </Card>
        <Card role="region" aria-label="Coverage report">
          <CardHeader>
            <CardTitle>Coverage report</CardTitle>
            <CardDescription>The Coverage screen as a PDF and a CSV: the share priced, the unpriced reasons with their remedies and the dollars waiting on mappings.</CardDescription>
          </CardHeader>
          <CardContent className="flex flex-col gap-3">
            <Link className="text-sm underline" href={`/p/${practiceId}/coverage`}>
              Open Coverage
            </Link>
            {canGenerate ? (
              <ActionForm action={generateReportDocumentFormAction} submit="Generate the coverage report" variant="outline">
                <input type="hidden" name="requestKey" value={randomUUID()} />
                <input type="hidden" name="practiceId" value={practiceId} />
                <input type="hidden" name="kind" value="coverage" />
              </ActionForm>
            ) : null}
          </CardContent>
        </Card>
      </div>
      <section aria-label="Generated reports" className="flex flex-col gap-2">
        <h2 className="text-lg font-semibold">Coverage reports and monthly summaries</h2>
        {documents.total === 0 ? (
          <p className="text-sm text-muted-foreground">None generated yet{canGenerate ? ': generate one above.' : '; a billing manager or analyst generates them.'}</p>
        ) : (
          <table className="w-full text-left text-sm" aria-label="Generated reports">
            <thead className="text-muted-foreground">
              <tr>
                <th className="py-1 font-medium">Report</th>
                <th className="py-1 font-medium">Figures fixed</th>
                <th className="py-1 font-medium">PDF</th>
                <th className="py-1 font-medium">Files</th>
              </tr>
            </thead>
            <tbody>
              {documents.items.map((document) => (
                <tr key={document.id} className="border-t" data-document={document.id}>
                  <td className="py-1 pr-3">
                    <Link className="underline" href={`${path}/documents/${document.id}`}>
                      {document.kind === 'coverage' ? 'Coverage report' : `Monthly summary, ${document.period ?? ''}`}
                    </Link>
                  </td>
                  <td className="py-1 pr-3">
                    {utc(document.generatedAt)} by {document.requestedBy ?? 'a member of the practice'}
                  </td>
                  <td className="py-1 pr-3">
                    <DocumentStatusBadge status={document.status} />
                  </td>
                  <td className="py-1">
                    <span className="flex flex-wrap gap-3">
                      {document.status === 'ready' ? (
                        <a className="underline" href={`${path}/documents/${document.id}/pdf`}>
                          PDF
                        </a>
                      ) : null}
                      <a className="underline" href={`${path}/documents/${document.id}/csv`}>
                        CSV
                      </a>
                    </span>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
        <Pager path={path} query={{ page: pageQuery.page, history: pageQuery.history }} page={documents.page} pages={documents.pages} total={documents.total} noun="Generated reports" param="documents" />
      </section>
      <section aria-label="Export history" className="flex flex-col gap-2">
        <h2 className="text-lg font-semibold">Export history</h2>
        <p className="text-sm text-muted-foreground">Every download of a report’s file and every line-level export, newest first, from the audit log.</p>
        {history.total === 0 ? (
          <p className="text-sm text-muted-foreground">No report file has been downloaded.</p>
        ) : (
          <table className="w-full text-left text-sm" aria-label="Exports">
            <thead className="text-muted-foreground">
              <tr>
                <th className="py-1 font-medium">When</th>
                <th className="py-1 font-medium">What</th>
                <th className="py-1 font-medium">By</th>
              </tr>
            </thead>
            <tbody>
              {history.items.map((entry) => {
                const href = exportHref(practiceId, entry);
                const what = `${FILE_WORDS[entry.file]} of ${entry.kind === 'monthly_summary' ? 'the monthly summary' : `a ${KIND_WORDS[entry.kind]}`}`;
                return (
                  <tr key={entry.eventId} className="border-t" data-export={entry.kind} data-line-level={entry.lineLevel ? 'yes' : 'no'}>
                    <td className="py-1 pr-3">{utc(entry.downloadedAt)}</td>
                    <td className="py-1 pr-3">
                      {href === null ? (
                        what
                      ) : (
                        <Link className="underline" href={href}>
                          {what}
                        </Link>
                      )}{' '}
                      {entry.lineLevel ? <Badge variant="outline">Line-level PHI</Badge> : null}
                    </td>
                    <td className="py-1">{entry.downloadedBy ?? 'a member of the practice'}</td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        )}
        <Pager path={path} query={{ page: pageQuery.page, documents: pageQuery.documents }} page={history.page} pages={history.pages} total={history.total} noun="Downloads" param="history" />
      </section>
      <Card role="region" aria-label="Share">
        <CardHeader>
          <CardTitle>Share within the organization</CardTitle>
          <CardDescription>Each report has its own link; this one opens this screen.</CardDescription>
        </CardHeader>
        <CardContent>
          <ShareLink href={`${origin}${path}`} />
        </CardContent>
      </Card>
    </AppShell>
  );
}
