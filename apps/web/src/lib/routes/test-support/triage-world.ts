import { randomUUID } from 'node:crypto';

import { type DatabaseClient, type DatabasePool, type KeyProvider, withJobScope, withPracticeScope } from '@tp/db';
import { asOwner } from '@tp/db/testing';
import { createLogger } from '@tp/observability';
import type { DocumentStore } from '@tp/worker/documents';
import { generateAuditReport } from '@tp/worker/runtime';

/**
 * Test support: triage of a route-test world's pricing run (docs/adr/0038), for the Anomalies, Cases
 * and Reports routes. Synthetic data only. Before the run is priced, a second line on the world's claim
 * paid below the signed-off schedule (97110 x 1 allowed 20.00 against 32.00: 12.00 short); after it,
 * an anomaly of the run, a case of that line's pattern with the line in it, actionable (its stage
 * events as triage records them), and two audit reports generated by the report job's code with a
 * stand-in printer: one unsigned, and one with the same numbers and files that the reviewer attested.
 */

export interface TriageLineOptions {
  readonly owner: DatabaseClient;
  readonly practiceId: string;
  readonly claimId: string;
  readonly planId: string;
}

/** The underpaid line, on the world's claim; returns its ID. */
export async function seedTriageLine(options: TriageLineOptions): Promise<string> {
  const { owner, practiceId } = options;
  return asOwner(owner, [practiceId], async () => {
    const { rows } = await owner.query<{ id: string }>(
      `INSERT INTO service_line (practice_id, claim_id, line_no, procedure_qualifier, procedure_code, modifiers, charge_cents, paid_cents, units, service_date,
         observed_allowed_cents, observed_allowed_basis, patient_share_cents, payer_plan_key)
       VALUES ($1, $2, 2, 'HC', '97110', '{GP}', 8000, 1600, 1, '2026-03-16', 2000, 'paid_plus_pr', 400, $3) RETURNING id`,
      [practiceId, options.claimId, options.planId],
    );
    return (rows[0] as { id: string }).id;
  });
}

export interface TriageWorldOptions {
  readonly owner: DatabaseClient;
  readonly app: DatabasePool;
  readonly keys: KeyProvider;
  readonly documents: DocumentStore;
  readonly practiceId: string;
  readonly pricingRunId: string;
  /** The world's first line (the anomaly flags it) and the underpaid line (the case holds it). */
  readonly flaggedLineId: string;
  readonly caseLineServiceLineId: string;
  readonly payerId: string;
  readonly planId: string;
  readonly signedOffVersionId: string;
  readonly managerId: string;
  /** A reimbursement reviewer holding a support grant on the practice. */
  readonly reviewerId: string;
}

export interface SeededTriage {
  readonly anomalyId: string;
  readonly caseId: string;
  readonly caseLineId: string;
  readonly auditReportId: string;
  readonly auditReportPdfSha256: string;
  readonly auditReportCsvSha256: string;
  readonly attestedReportId: string;
}

/** A stand-in for Chromium's PDF, its own for each world (two worlds never share a file's SHA-256). */
const standInPdf = () => new TextEncoder().encode(`%PDF-1.7\n% SYNTHETIC stand-in for the route tests ${randomUUID()}\n`);

export async function seedTriage(options: TriageWorldOptions): Promise<SeededTriage> {
  const { owner, app, practiceId } = options;
  const seeded = await asOwner(owner, [practiceId], async () => {
    const one = async (sql: string, values: unknown[]) => ((await owner.query<{ id: string }>(sql, values)).rows[0] as { id: string }).id;
    const cohortKey = { payer_id: options.payerId, plan_id: options.planId, procedure_code: '97110', modifiers: ['GP'], place_of_service: '11', quarter: '2026-Q1' };
    const stats = {
      format: 'tp-anomaly-stats/1',
      label: 'investigatory',
      basis: 'observed_allowed_per_unit',
      lines: 30,
      min_cents: '4000',
      p25_cents: '5500',
      median_cents: '5500',
      p75_cents: '5500',
      max_cents: '5600',
      modal_cents: '5500',
      modal_lines: 29,
      threshold_cents: '500',
      below_mode_lines: 1,
      flagged_lines: 1,
      flagged_observed_cents: '11000',
      range_low_cents: '0',
      range_high_cents: '0',
    };
    const anomalyId = await one(
      'INSERT INTO anomaly (practice_id, pricing_run_id, cohort_key, cohort_size, modal_allowed_cents, stats, line_ids) VALUES ($1, $2, $3, 30, 5500, $4, $5) RETURNING id',
      [practiceId, options.pricingRunId, JSON.stringify(cohortKey), JSON.stringify(stats), [options.flaggedLineId]],
    );
    const pricedLineId = await one('SELECT id FROM priced_line WHERE pricing_run_id = $1 AND service_line_id = $2', [options.pricingRunId, options.caseLineServiceLineId]);
    const rateRecordId = await one('SELECT rate_record_id AS id FROM priced_line WHERE id = $1', [pricedLineId]);
    const patternKey = { payer_id: options.payerId, plan_id: options.planId, mapping_kind: 'contract', contract_version_id: options.signedOffVersionId, rate_record_id: rateRecordId, behavior: 'BELOW_CONTRACT_RATE' };
    const caseId = await one('INSERT INTO "case" (practice_id, pattern_key, payer_id, plan_id, rate_record_id, materiality_cents) VALUES ($1, $2, $3, $4, $5, 25000) RETURNING id', [
      practiceId,
      JSON.stringify(patternKey),
      options.payerId,
      options.planId,
      rateRecordId,
    ]);
    for (const stage of ['validated', 'actionable']) {
      await owner.query('INSERT INTO line_status (practice_id, service_line_id, stage, priced_line_id) VALUES ($1, $2, $3, $4)', [practiceId, options.caseLineServiceLineId, stage, pricedLineId]);
    }
    const caseLineId = await one('INSERT INTO case_line (practice_id, case_id, service_line_id, priced_line_id) VALUES ($1, $2, $3, $4) RETURNING id', [
      practiceId,
      caseId,
      options.caseLineServiceLineId,
      pricedLineId,
    ]);
    const auditReportId = await one('INSERT INTO audit_report (practice_id, pricing_run_id, requested_by) VALUES ($1, $2, $3) RETURNING id', [practiceId, options.pricingRunId, options.managerId]);
    return { anomalyId, caseId, caseLineId, auditReportId };
  });
  const jobId = randomUUID();
  const generated = await generateAuditReport(
    { jobId, logger: createLogger({ sink: () => undefined }), transaction: (work) => withJobScope(app, { jobId, practiceId }, work) },
    { documents: options.documents, keys: options.keys, pdf: { render: () => Promise.resolve(standInPdf()) } },
    practiceId,
    seeded.auditReportId,
  );
  if (generated.outcome !== 'ready') {
    throw new Error('the seeded audit report was not generated');
  }
  // A second report with the same numbers and files, made ready by the owner (not a person), then attested by the reviewer.
  const attestedReportId = await asOwner(owner, [practiceId], async () => {
    const { rows } = await owner.query<{ id: string }>(
      `INSERT INTO audit_report (practice_id, pricing_run_id, requested_by) SELECT practice_id, pricing_run_id, requested_by FROM audit_report WHERE id = $1 RETURNING id`,
      [seeded.auditReportId],
    );
    const id = (rows[0] as { id: string }).id;
    await owner.query(
      `UPDATE audit_report a SET status = 'ready', as_of = s.as_of, content = s.content, pdf_key = s.pdf_key, pdf_sha256 = s.pdf_sha256, csv_key = s.csv_key, csv_sha256 = s.csv_sha256
         FROM audit_report s WHERE a.id = $1 AND s.id = $2`,
      [id, seeded.auditReportId],
    );
    return id;
  });
  await withPracticeScope(app, { actorId: options.reviewerId, practiceIds: [practiceId] }, (scope) =>
    scope.client.query('UPDATE audit_report SET attested_by = app_actor_id(), attestation = $2 WHERE id = $1', [
      attestedReportId,
      JSON.stringify({ format: 'tp-attestation/1', checklist: ['coverage'], pdf_sha256: generated.pdfSha256, csv_sha256: generated.csvSha256 }),
    ]),
  );
  return { ...seeded, auditReportPdfSha256: generated.pdfSha256, auditReportCsvSha256: generated.csvSha256, attestedReportId };
}
