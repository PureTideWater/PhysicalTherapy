    const pdf = await w.stored(practice, row.pdf_key ?? '');
    const csv = await w.stored(practice, row.csv_key ?? '');
    expect(sha256(pdf)).toBe(row.pdf_sha256);
    expect(sha256(csv)).toBe(row.csv_sha256);
    expect(pdf.subarray(0, 5).toString('latin1')).toBe('%PDF-');

    // The headline: actionable, payer approved, recovered; flagged and validated below, each its own stage.
