-- The v1 reports' printed documents and the Reports screen's export history (PRD 5, J12; PRD 6, Reports
-- and exports: "audit report; monthly summary; ROI statement; coverage report; portfolio; CSV and PDF;
-- line-level exports role-gated and logged"; PRD 7, Reports: "generate, download, share within the
-- organization ... export history"; docs/adr/0040: the monthly summary's PDF and the coverage report
-- come with the other v1 reports and share the audit report's PDF pipeline; docs/adr/0045).
--
-- One PHI table, with practice_id NOT NULL (indexed), ENABLE and FORCE ROW LEVEL SECURITY, the
-- registered tenant policy and a row in phi_table_registry:
--
-- - report_document: a coverage report (the Coverage screen of the run in effect) or a month's variance
--   summary, generated by a person who works cases, in their own name, with its figures fixed as
--   generated (content: counts, integer cents as text, codes, and the payers' and plans' names the 835s
--   carry; no patient, claim or line identifier). The worker's report_document job prints it to PDF
--   through the audit report's Chromium pipeline and records the PDF's key (under the document's own
--   practice and ID) and SHA-256, once, in no one's name; nothing else about a document ever changes,
--   and none is deleted. Its CSV is computed from the stored figures on every download.
--
-- And:
--
-- - job type report_document: the print job.
-- - practice_export_history(practice, limit, offset) and practice_export_count(practice): every
--   download of a report's file and every line-level export (audit reports, ROI statements, report
--   documents, the monthly summary's CSV, packet exports), read from the audit log, which records each
--   one. The audit log is the practice administrators' to read (its access log); these answer report
--   readers (report.read) of a practice they reach, with the download events alone: what was
--   downloaded (codes and opaque IDs), by whom (an opaque ID) and when.
--
-- Runs as tp_owner. Safe with the previous image running: a new table, a wider job type list and two
-- new functions; the previous image neither reads nor writes them.

