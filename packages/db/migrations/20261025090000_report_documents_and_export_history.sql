-- ---------------------------------------------------------------------------------------------------
-- report_document
-- ---------------------------------------------------------------------------------------------------

CREATE TABLE report_document (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  practice_id uuid NOT NULL REFERENCES practice (id),
  kind text NOT NULL CHECK (kind IN ('coverage', 'monthly_summary')),
  -- The month a monthly summary covers (YYYY-MM); null for a coverage report.
  period text CHECK (period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  -- The pricing run in effect a coverage report read its shares and reasons from; null before any.
  pricing_run_id uuid REFERENCES pricing_run (id),
  requested_by uuid NOT NULL REFERENCES "user" (id),
  -- tp-coverage-report/1 or tp-monthly-summary/1: every figure the document shows, kept as generated.
  content jsonb NOT NULL CHECK (jsonb_typeof(content) = 'object'),
  status text NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'ready', 'failed')),
  -- The stored PDF (an opaque key: practice, document, object) and the SHA-256 of its plaintext.
  pdf_key text CHECK (pdf_key ~ '^practices/[0-9a-f-]{36}/reports/[0-9a-f-]{36}/[0-9a-f-]{36}\.pdf$'),
  pdf_sha256 text CHECK (pdf_sha256 ~ '^[0-9a-f]{64}$'),
  failure_code text CHECK (failure_code ~ '^[a-z][a-z0-9_]{0,63}$'),
  -- When its figures were fixed, and when its PDF was recorded.
  generated_at timestamptz NOT NULL DEFAULT now(),
  printed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT report_document_period_of_a_month CHECK ((kind = 'monthly_summary') = (period IS NOT NULL)),
  CONSTRAINT report_document_run_of_coverage CHECK (kind = 'coverage' OR pricing_run_id IS NULL),
  CONSTRAINT report_document_format CHECK (content ->> 'format' = CASE kind WHEN 'coverage' THEN 'tp-coverage-report/1' ELSE 'tp-monthly-summary/1' END),
  CONSTRAINT report_document_ready_with_its_pdf CHECK ((status = 'ready') = (pdf_key IS NOT NULL AND pdf_sha256 IS NOT NULL AND printed_at IS NOT NULL)),
  CONSTRAINT report_document_failure_when_failed CHECK ((status = 'failed') = (failure_code IS NOT NULL))
);
CREATE INDEX report_document_by_practice ON report_document (practice_id, generated_at DESC, id);

