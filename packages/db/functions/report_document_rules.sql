CREATE OR REPLACE FUNCTION public.report_document_rules()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'pg_catalog', 'public', 'pg_temp'
AS $function$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'a report document keeps its figures; a new one is generated' USING ERRCODE = 'check_violation';
  END IF;
  IF TG_OP = 'INSERT' THEN
    IF NEW.status IS DISTINCT FROM 'queued' OR NEW.pdf_key IS NOT NULL OR NEW.pdf_sha256 IS NOT NULL OR NEW.printed_at IS NOT NULL OR NEW.failure_code IS NOT NULL THEN
      RAISE EXCEPTION 'a report document is printed after it is generated' USING ERRCODE = 'check_violation';
    END IF;
    NEW.generated_at := now();
    IF practice_in_scope(NEW.practice_id) AND (NOT app_actor_is_person() OR NEW.requested_by IS DISTINCT FROM app_actor_id()
       OR NOT coalesce(app_actor_permitted(NEW.practice_id, 'case.work'), false)) THEN
      RAISE EXCEPTION 'a report document is generated by a person who works the practice''s cases, in their own name' USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN NEW;
  END IF;
  IF (NEW.id, NEW.practice_id, NEW.kind, NEW.period, NEW.pricing_run_id, NEW.requested_by, NEW.content, NEW.generated_at, NEW.created_at)
     IS DISTINCT FROM (OLD.id, OLD.practice_id, OLD.kind, OLD.period, OLD.pricing_run_id, OLD.requested_by, OLD.content, OLD.generated_at, OLD.created_at)
     OR OLD.status <> 'queued' OR NEW.status = 'queued' THEN
    RAISE EXCEPTION 'a report document keeps its figures; only its printed PDF, or the print''s failure, is recorded, once' USING ERRCODE = 'check_violation';
  END IF;
  IF practice_in_scope(NEW.practice_id) AND app_actor_is_person() THEN
    RAISE EXCEPTION 'the print job records the printed PDF, in no one''s name' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF NEW.status = 'ready' THEN
    IF left(NEW.pdf_key, char_length('practices/' || NEW.practice_id::text || '/reports/' || NEW.id::text || '/')) <> 'practices/' || NEW.practice_id::text || '/reports/' || NEW.id::text || '/' THEN
      RAISE EXCEPTION 'a report document''s PDF is stored under its own practice and document' USING ERRCODE = 'check_violation';
    END IF;
    NEW.printed_at := now();
  ELSIF NEW.pdf_key IS NOT NULL OR NEW.pdf_sha256 IS NOT NULL THEN
    RAISE EXCEPTION 'a failed print records no PDF' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$function$;
