import { Duration, RemovalPolicy, aws_iam as iam, type aws_kms as kms, aws_s3 as s3 } from 'aws-cdk-lib';
import { Construct } from 'constructs';

import { BACKUP_RETENTION_DAYS, RECORD_RETENTION_YEARS } from '../retention';

/**
 * A private bucket with the controls every bucket in the stack shares (PRD 16, encryption and
 * backups): SSE-KMS under the environment key with an S3 bucket key (the at-rest layer; the
 * application's buckets also hold only objects the application sealed with a per-practice key,
 * docs/adr/0018), all four public-access blocks,
 * a bucket policy that refuses any request not over TLS 1.2 or later, versioning, ACLs disabled,
 * and retention when the stack is deleted. Names are generated by CloudFormation; object keys are
 * opaque IDs chosen by the application (PRD 16, logging discipline: no PHI in S3 keys).
 */
export function privateBucket(scope: Construct, id: string, key: kms.IKey, extra: Partial<s3.BucketProps> = {}): s3.Bucket {
  return new s3.Bucket(scope, id, {
    encryption: s3.BucketEncryption.KMS,
    encryptionKey: key,
    bucketKeyEnabled: true,
    blockPublicAccess: s3.BlockPublicAccess.BLOCK_ALL,
    enforceSSL: true,
    minimumTLSVersion: 1.2,
    versioned: true,
    objectOwnership: s3.ObjectOwnership.BUCKET_OWNER_ENFORCED,
    removalPolicy: RemovalPolicy.RETAIN,
    ...extra,
  });
}

/**
 * Refuses, for everyone, any object write that could replace an existing key: PutObject, CopyObject
 * and CompleteMultipartUpload must carry If-None-Match (S3 conditional writes; UploadPart is not an
 * object-creating operation and stays allowed). Stored originals, packets and audit copies are
 * written once (PRD 6, Intake: "original bytes kept immutable"; PRD 19, write-once copies).
 */
export function denyOverwrites(bucket: s3.Bucket): void {
  bucket.addToResourcePolicy(
    new iam.PolicyStatement({
      sid: 'WriteOnceKeys',
      effect: iam.Effect.DENY,
      principals: [new iam.AnyPrincipal()],
      actions: ['s3:PutObject'],
      resources: [bucket.arnForObjects('*')],
      conditions: { Null: { 's3:if-none-match': 'true' }, Bool: { 's3:ObjectCreationOperation': 'true' } },
    }),
  );
}

/** Where browsers upload documents before their malware scan (documentIntakeKey in packages/db). */
export const INTAKE_PREFIX = 'intake/';

/** Where intake puts a clean scanned document's bytes for Textract to read (apps/worker/src/intake/textract-staging.ts). */
export const TEXTRACT_STAGING_PREFIX = 'textract/';

/**
 * The headers a presigned upload PUT carries from the browser (apps/web/src/lib/uploads/targets.ts,
 * SIGNED_HEADERS; Content-Length is the browser's own and never needs CORS).
 */
export const UPLOAD_HEADERS = ['content-type', 'if-none-match', 'x-amz-server-side-encryption', 'x-amz-server-side-encryption-aws-kms-key-id'] as const;

/** How long a browser may keep the documents bucket's CORS answer. */
export const UPLOAD_CORS_MAX_AGE_SECONDS = 600;

export interface StorageProps {
  readonly key: kms.IKey;
  readonly objectLockMode: 'COMPLIANCE' | 'GOVERNANCE';
  /** The application's origin, the only one whose pages may PUT presigned uploads (https://<AppDomainName>). */
  readonly uploadOrigin: string;
}

/**
 * The application's buckets (PRD 15, Stack: files).
 *
 * - `documents`: uploaded originals (835s, contracts, exhibits, exports). Versioned, so a deleted
 *   object survives as a noncurrent version for the backup window; no key is ever overwritten
 *   (denyOverwrites), so an original cannot be replaced; GuardDuty scans every new object
 *   (AccountSecurity). Incomplete multipart uploads are aborted after a week. Browsers upload under
 *   `intake/` (presigned PUTs), where GuardDuty scans the plaintext before the worker seals it under
 *   the practice's key elsewhere; nothing reads an intake object again, so it, its noncurrent
 *   version and its delete marker expire after a day (docs/adr/0018 and 0026). Intake puts a clean
 *   scanned document's bytes under `textract/` for Textract to read, and those expire the same way
 *   (docs/adr/0055). CORS admits a PUT
 *   from the application's origin alone, with exactly the headers the presigned PUT signs, and
 *   exposes nothing (docs/adr/0049).
 * - `packets` and `auditCopies`: exported packets and the nightly audit_event copies. Versioned
 *   with Object Lock and a default retention of seven years (PRD 19: write-once, seven years), and
 *   written once per key as well.
 */
export class Storage extends Construct {
  readonly documents: s3.Bucket;
  readonly packets: s3.Bucket;
  readonly auditCopies: s3.Bucket;

  constructor(scope: Construct, id: string, props: StorageProps) {
    super(scope, id);
    this.documents = privateBucket(this, 'Documents', props.key, {
      lifecycleRules: [
        {
          id: 'noncurrent-versions-follow-the-backup-window',
          noncurrentVersionExpiration: Duration.days(BACKUP_RETENTION_DAYS),
          abortIncompleteMultipartUploadAfter: Duration.days(7),
        },
        {
          id: 'intake-uploads-expire',
          prefix: INTAKE_PREFIX,
          expiration: Duration.days(1),
          noncurrentVersionExpiration: Duration.days(1),
        },
        {
          id: 'intake-delete-markers-expire',
          prefix: INTAKE_PREFIX,
          expiredObjectDeleteMarker: true,
        },
        {
          id: 'textract-copies-expire',
          prefix: TEXTRACT_STAGING_PREFIX,
          expiration: Duration.days(1),
          noncurrentVersionExpiration: Duration.days(1),
        },
        {
          id: 'textract-delete-markers-expire',
          prefix: TEXTRACT_STAGING_PREFIX,
          expiredObjectDeleteMarker: true,
        },
      ],
      cors: [
        {
          id: 'presigned-uploads-from-the-application',
          allowedOrigins: [props.uploadOrigin],
          allowedMethods: [s3.HttpMethods.PUT],
          allowedHeaders: [...UPLOAD_HEADERS],
          maxAge: UPLOAD_CORS_MAX_AGE_SECONDS,
        },
      ],
    });
    this.packets = this.writeOnceBucket('Packets', props);
    this.auditCopies = this.writeOnceBucket('AuditCopies', props);
    for (const bucket of [this.documents, this.packets, this.auditCopies]) {
      denyOverwrites(bucket);
    }
  }

  private writeOnceBucket(id: string, props: StorageProps): s3.Bucket {
    const bucket = privateBucket(this, id, props.key, { objectLockEnabled: true });
    // The L2 construct can express the default retention only in days, which drifts from seven
    // calendar years by the leap days; S3 takes Years directly.
    const resource = bucket.node.defaultChild as s3.CfnBucket;
    resource.objectLockConfiguration = {
      objectLockEnabled: 'Enabled',
      rule: { defaultRetention: { mode: props.objectLockMode, years: RECORD_RETENTION_YEARS } },
    };
    return bucket;
  }
}
