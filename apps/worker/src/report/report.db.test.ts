/**
 * The audit report job against PostgreSQL (PRD 4, Audit v0; PRD 5, J12; PRD 6, Reports and exports;
 * test matrix CAS-02, CAS-07): SYNTHETIC CAS fixtures parsed, priced and triaged in their own
 * practices, reports requested in the billing manager's name and generated by the report job's code,
 * printed to PDF by Playwright's Chromium where it is installed, stored sealed with the practice's key
 * and recorded with their SHA-256; then attested by a reimbursement reviewer under a support grant and
 * released by a person who works cases.
 */

let w: TriageWorld;

beforeAll(async () => {
  w = await TriageWorld.open(readDatabaseUrl());
}, 60_000);

afterAll(async () => {
  await w.close();
});

const FIXED = { schedule: [{ code: '97110', amountCents: '5000' }], effectiveFrom: '2026-01-01', disputeWindowDays: 3650 };

interface ReportRow {
  status: string;
  as_of: string | null;
  content: AuditReportContent | null;
  pdf_key: string | null;
  pdf_sha256: string | null;
  csv_key: string | null;
  csv_sha256: string | null;
  attested_by: string | null;
  attested_at: Date | null;
  released_by: string | null;
  released_at: Date | null;
  failure_code: string | null;
}

const sha256 = (bytes: Uint8Array) => createHash('sha256').update(bytes).digest('hex');

function inScope<T>(target: Practice, actorId: string, sql: string, values: unknown[] = []): Promise<T[]> {
  return withPracticeScope(w.app, { actorId, practiceIds: [target.practiceId] }, async (scope) => (await scope.client.query<T & object>(sql, values)).rows);
}

async function report(target: Practice, id: string): Promise<ReportRow> {
  const [row] = await inScope<ReportRow>(
    target,
    target.manager,
    'SELECT status, as_of::text, content, pdf_key, pdf_sha256, csv_key, csv_sha256, attested_by, attested_at, released_by, released_at, failure_code FROM audit_report WHERE id = $1',
    [id],
  );
  if (row === undefined) {
    throw new Error('no such report');
  }
  return row;
}

/** CAS-03 in a practice of its own: two fixed-schedule contracts, March priced, ready for a report. */
async function cas03(label: string): Promise<{ practice: Practice; runId: string }> {
  const practice = await w.practice(label);
  await w.load(practice, 'CAS-03/remit.835');
  const one = await w.fixedContract(practice, FIXED);
  const two = await w.fixedContract(practice, { ...FIXED, schedule: [{ code: '97530', amountCents: '5200' }] });
  const runId = await w.pricedRun(practice, {
    plans: [
      { key: 'CE:SYNPLAN-FIX-ONE', versionId: one.versionId },
      { key: 'CE:SYNPLAN-FIX-TWO', versionId: two.versionId },
    ],
    from: '2026-03-01',
    to: '2026-03-31',
  });
  return { practice, runId };
}

function csvRows(csv: Buffer): string[][] {
  const text = csv.toString('utf8');
  expect(text.endsWith('\r\n')).toBe(true);
  return text
    .slice(0, -2)
    .split('\r\n')
    .map((row) => row.split(','));
}

describe('generating an audit report (PRD 4, Audit v0)', () => {
  it('triages the run, records the numbers, stores the PDF and the line CSV with their SHA-256, and leaves a generated report as it is', async () => {
    const { practice, runId } = await cas03('report CAS-03');
    const id = await w.requestReport(practice, runId);
    expect(await report(practice, id)).toMatchObject({ status: 'queued', content: null, pdf_key: null });

    const outcome = await w.generate(practice, id);
    const row = await report(practice, id);
    expect(outcome).toEqual({ outcome: 'ready', pdfSha256: row.pdf_sha256, csvSha256: row.csv_sha256 });
    expect(row).toMatchObject({ status: 'ready', as_of: todayUtc() });
    expect(row.pdf_key).toMatch(new RegExp(`^practices/${practice.practiceId}/reports/${id}/[0-9a-f-]{36}\\.pdf$`));
    expect(row.csv_key).toMatch(new RegExp(`^practices/${practice.practiceId}/reports/${id}/[0-9a-f-]{36}\\.csv$`));

    // The stored objects are the files the hashes name.
    const pdf = await w.stored(practice, row.pdf_key ?? '');
    const csv = await w.stored(practice, row.csv_key ?? '');
    expect(sha256(pdf)).toBe(row.pdf_sha256);
    expect(sha256(csv)).toBe(row.csv_sha256);
    expect(pdf.subarray(0, 5).toString('latin1')).toBe('%PDF-');

    // The headline: actionable, payer approved, recovered; flagged and validated below, each its own stage.
    const content = row.content as AuditReportContent;
    expect(content).toMatchObject({ format: 'tp-audit-report/1', report_id: id, as_of: todayUtc(), run: { pricing_run_id: runId, period_from: '2026-03-01', period_to: '2026-03-31', release_no: 900001 } });
    expect(content.headline).toMatchObject({
      actionable_cents: '55200',
      actionable_lines: 16,
      payer_approved_cents: '0',
      recovered_cents: '0',
      flagged_lines: 0,
      validated_lines: 16,
      validated_cents: '55200',
    });
    expect(content.coverage).toMatchObject({ lines: 16, priced_lines: 16, reasons: [] });
    expect(content.cases.map((item) => [item.plan, item.state, item.lines, item.actionable_cents, item.deadline_on, item.behavior])).toEqual([
      ['CE:SYNPLAN-FIX-ONE', 'open', 8, '28000', '2036-03-29', 'BELOW_CONTRACT_RATE'],
      ['CE:SYNPLAN-FIX-TWO', 'open', 8, '27200', '2036-03-29', 'BELOW_CONTRACT_RATE'],
    ]);
    // No pursuit settings: the cost is not estimated, and the gap says so.
    expect(content.pursuit).toEqual({ estimated: false, cost_cents: null, net_expected_cents: null });
    expect(content.evidence_gaps.map((gap) => gap.kind)).toContain('pursuit_settings');

    // One CSV row per line of the run, each linked to its stage and case; the case totals are the sums of their lines.
    const [header, ...lines] = csvRows(csv);
    expect(header).toEqual([...CSV_COLUMNS]);
    expect(lines).toHaveLength(16);
    const column = (name: (typeof CSV_COLUMNS)[number]) => CSV_COLUMNS.indexOf(name);
    expect(new Set(lines.map((line) => line[column('stage')]))).toEqual(new Set(['actionable']));
    expect(new Set(lines.map((line) => line[column('counted_as')]))).toEqual(new Set(['actionable']));
    for (const item of content.cases) {
      const ofCase = lines.filter((line) => line[column('case_ref')] === item.case_id);
      expect(ofCase).toHaveLength(item.lines);
      const total = ofCase.reduce((sum, line) => sum + BigInt((line[column('variance')] ?? '').replace('.', '')), 0n);
      expect(total.toString()).toBe(item.actionable_cents);
    }

    // Reading the lines for the report is recorded in the audit log.
    const audited = await asOwner(w.owner, [practice.practiceId], async () =>
      (await w.owner.query<{ events: string }>("SELECT count(*)::text AS events FROM audit_event WHERE practice_id = $1 AND object_type = 'priced_line' AND purpose = 'audit_report'", [practice.practiceId])).rows,
    );
    expect(Number(audited[0]?.events)).toBeGreaterThan(0);

    // Generated once: a second attempt leaves it as it is.
    expect(await w.generate(practice, id)).toEqual({ outcome: 'already_finished', status: 'ready' });
    expect((await report(practice, id)).pdf_sha256).toBe(row.pdf_sha256);
  }, 120_000);

  it.skipIf(!chromiumInstalled())('prints the report’s numbers and stage labels into the PDF (skipped where Playwright’s Chromium is not installed)', async () => {
    const { practice, runId } = await cas03('report PDF');
    const id = await w.requestReport(practice, runId);
    await w.generate(practice, id);
    const row = await report(practice, id);
    const read = await readDocumentPages({ bytes: await w.stored(practice, row.pdf_key ?? ''), contentType: 'application/pdf' });
    const text = read.ok ? read.pages.join('\n') : '';
    expect(text).toContain('$552.00');
    // The headline's labels print in capitals.
    expect(text).toMatch(/Payer approved/i);
    expect(text).toMatch(/Recovered/i);
    expect(text).toContain('Flagged (investigatory)');
    expect(text).toContain('Validated');
  }, 120_000);

  it('keeps an anomaly investigatory and in no total (CAS-02)', async () => {
    const practice = await w.practice('report CAS-02', { anomaly_threshold_cents: '1000' });
    await w.load(practice, 'CAS-02/remit.835');
    const runId = await w.pricedRun(practice, { plans: [{ key: 'CE:SYNPLAN-OON-CAS', versionId: null, kind: 'no_agreement' }], from: '2026-04-01', to: '2026-06-30' });
    const id = await w.requestReport(practice, runId);
    expect((await w.generate(practice, id)).outcome).toBe('ready');
    const row = await report(practice, id);
    const content = row.content as AuditReportContent;
    expect(content.headline).toMatchObject({ actionable_cents: '0', actionable_lines: 0, validated_lines: 0, validated_cents: '0', flagged_lines: 4, flagged_range_low_cents: '4000', flagged_range_high_cents: '8000' });
    expect(content.anomalies).toHaveLength(1);
    expect(content.anomalies[0]).toMatchObject({ label: 'investigatory', procedure_code: '97110', cohort_size: 32, modal_allowed_cents: '9000', flagged_lines: 4 });
    expect(content.cases).toEqual([]);
    expect(content.coverage).toMatchObject({ lines: 32, priced_lines: 0, reasons: [{ reason: 'NO_AGREEMENT', lines: 32 }] });
    const [, ...lines] = csvRows(await w.stored(practice, row.csv_key ?? ''));
    const column = (name: (typeof CSV_COLUMNS)[number]) => CSV_COLUMNS.indexOf(name);
    const flagged = lines.filter((line) => line[column('stage')] === 'flagged');
    expect(flagged).toHaveLength(4);
    expect(new Set(flagged.map((line) => line[column('anomaly_ref')]))).toEqual(new Set([content.anomalies[0]?.anomaly_id]));
    expect(new Set(lines.map((line) => line[column('counted_as')]))).toEqual(new Set(['unpriced']));
  }, 120_000);

  it('keeps a report’s numbers when a line is reopened after it (CAS-07)', async () => {
    const { practice, runId } = await cas03('report CAS-07');
    // Triage, then write a line of plan one off before the first report.
    const first = await w.requestReport(practice, runId);
    await w.generate(practice, first);
    const [line] = await inScope<{ id: string }>(
      practice,
      practice.manager,
      "SELECT cl.id FROM case_line cl JOIN \"case\" c ON c.id = cl.case_id JOIN plan pl ON pl.id = c.plan_id WHERE pl.plan_key = 'CE:SYNPLAN-FIX-ONE' ORDER BY cl.id LIMIT 1",
    );
    await inScope(practice, practice.manager, "UPDATE case_line SET written_off_reason = 'not_worth_pursuit', written_off_by = $2 WHERE id = $1", [line?.id, practice.manager]);
    const before = await w.requestReport(practice, runId);
    await w.generate(practice, before);
    const generated = await report(practice, before);
    expect((generated.content as AuditReportContent).headline.actionable_cents).toBe('51700');
    expect((generated.content as AuditReportContent).validated.not_actionable).toEqual([{ reason: 'written_off:not_worth_pursuit', lines: 1, variance_cents: '3500' }]);

    await inScope(practice, practice.manager, 'UPDATE case_line SET written_off_reason = NULL, written_off_by = NULL, reopen_reason = $2, reopened_by = $3 WHERE id = $1', [line?.id, 'enc:v1:SYNTHETIC-REOPEN', practice.manager]);
    const after = await w.requestReport(practice, runId);
    await w.generate(practice, after);
    expect((await report(practice, after)).content?.headline.actionable_cents).toBe('55200');
    // The report generated before the reopen keeps its numbers, its files and their hashes.
    const kept = await report(practice, before);
    expect(kept).toEqual(generated);
    expect(sha256(await w.stored(practice, kept.csv_key ?? ''))).toBe(generated.csv_sha256);
    expect((await report(practice, first)).content?.headline.actionable_cents).toBe('55200');
  }, 120_000);

  it('refuses a report of a run that is not complete, and marks a report failed on the last attempt', async () => {
    const practice = await w.practice('report failing');
    await w.load(practice, 'CAS-05/remit.835');
    const contract = await w.fixedContract(practice, FIXED);
    await w.pricing.mapped(practice, await w.pricing.planOf(practice, 'CE:SYNPLAN-FIX-ONE'), 'contract', '2026-01-01', contract.versionId);
    const queuedRun = await w.pricing.createRun(practice, '2026-03-01', '2026-03-31');
    const id = await w.requestReport(practice, queuedRun);
    expect(await w.generate(practice, id)).toEqual({ outcome: 'not_complete' });
    expect((await report(practice, id)).status).toBe('queued');

    await w.pricing.execute(practice, queuedRun);
    const failing = auditReportHandler({ ...w.services, pdf: { render: () => Promise.reject(new Error('SYNTHETIC printer failure')) } });
    await expect(failing({ practice_id: practice.practiceId, audit_report_id: id }, w.pricing.jobContext(practice.practiceId))).rejects.toThrow(/printer/);
    expect((await report(practice, id)).status).toBe('queued');
    await expect(failing({ practice_id: practice.practiceId, audit_report_id: id }, w.pricing.jobContext(practice.practiceId, [], true))).rejects.toThrow(/printer/);
    expect(await report(practice, id)).toMatchObject({ status: 'failed', failure_code: 'generation_failed', content: null });
    // Nothing was stored for the failed attempts' report.
    expect((await report(practice, id)).pdf_key).toBeNull();
  }, 120_000);
});

describe('the reviewer’s attestation and the release (PRD 4: an independent reviewer signs before release)', () => {
  it('lets a reimbursement reviewer under a support grant attest a ready report once, and a person who works cases release it only then', async () => {
    const { practice, runId } = await cas03('report attestation');
    const id = await w.requestReport(practice, runId);
    const internal = await createOrganization(w.owner, 'internal', 'review');
    const reviewer = await createUser(w.owner, { hardwareKeyRequired: true });
    await addMembership(w.owner, internal, reviewer, 'reviewer');
    await asOwner(w.owner, [practice.practiceId], () =>
      w.owner.query(`INSERT INTO support_grant (practice_id, user_id, ticket, reason, expires_at) VALUES ($1, $2, 'RV-1', 'SYNTHETIC AUDIT REVIEW', now() + interval '4 hours')`, [practice.practiceId, reviewer]),
    );
    const viewer = await createUser(w.owner);
    await addMembership(w.owner, practice.world.organizationId, viewer, 'viewer');
    const signed = (files: { pdf_sha256: string | null; csv_sha256: string | null }, statement = 'SYNTHETIC attestation') =>
      JSON.stringify({ checklist: ['coverage', 'anomalies', 'validated', 'actionable', 'evidence_gaps'], statement, pdf_sha256: files.pdf_sha256, csv_sha256: files.csv_sha256 });
    const attest = (actorId: string, attestation: string) => inScope(practice, actorId, 'UPDATE audit_report SET attested_by = $2, attestation = $3 WHERE id = $1', [id, actorId, attestation]);
    const release = (actorId: string) => inScope(practice, actorId, 'UPDATE audit_report SET released_by = $2 WHERE id = $1', [id, actorId]);

    // Queued: nothing to attest yet, and a person never generates it.
    await expect(attest(reviewer, signed({ pdf_sha256: null, csv_sha256: null }))).rejects.toMatchObject({ code: '23514' });
    await expect(inScope(practice, practice.manager, "UPDATE audit_report SET status = 'failed', failure_code = 'by_hand' WHERE id = $1", [id])).rejects.toMatchObject({ code: '42501' });
    await w.generate(practice, id);
    const generated = await report(practice, id);
    const attestation = signed(generated);

    // Unsigned, it is never released.
    await expect(release(practice.manager)).rejects.toThrow(/before a reimbursement reviewer signs/);
    // Only a reviewer attests, in their own name, over the files the report names.
    await expect(attest(practice.manager, attestation)).rejects.toMatchObject({ code: '42501' });
    await expect(inScope(practice, reviewer, 'UPDATE audit_report SET attested_by = $2, attestation = $3 WHERE id = $1', [id, practice.manager, attestation])).rejects.toMatchObject({ code: '42501' });
    await expect(attest(reviewer, signed({ pdf_sha256: 'f'.repeat(64), csv_sha256: generated.csv_sha256 }))).rejects.toThrow(/SHA-256 of the report/);
    await attest(reviewer, attestation);
    const attested = await report(practice, id);
    expect(attested).toMatchObject({ attested_by: reviewer, released_by: null });
    expect(attested.attested_at).toBeInstanceOf(Date);
    // Signed once: the same signature again changes nothing; another is refused.
    await attest(reviewer, attestation);
    expect((await report(practice, id)).attested_at).toEqual(attested.attested_at);
    await expect(attest(reviewer, signed(generated, 'SYNTHETIC second thoughts'))).rejects.toThrow(/attested once/);
    // The reviewer edits nothing else: not the release, not the numbers.
    await expect(release(reviewer)).rejects.toMatchObject({ code: '42501' });
    await expect(release(viewer)).rejects.toMatchObject({ code: '42501' });
    await expect(inScope(practice, practice.manager, "UPDATE audit_report SET content = '{}'::jsonb WHERE id = $1", [id])).rejects.toThrow(/never change once generated/);
    await release(practice.manager);
    const released = await report(practice, id);
    expect(released).toMatchObject({ released_by: practice.manager, content: generated.content, pdf_sha256: generated.pdf_sha256 });
    expect(released.released_at).toBeInstanceOf(Date);
    // Released once: the same release again changes nothing; another person's is refused.
    await release(practice.manager);
    expect((await report(practice, id)).released_at).toEqual(released.released_at);
    const another = await createUser(w.owner);
    await addMembership(w.owner, practice.world.organizationId, another, 'billing_manager');
    await expect(release(another)).rejects.toThrow(/released once/);
    await expect(inScope(practice, practice.manager, 'DELETE FROM audit_report WHERE id = $1', [id])).rejects.toMatchObject({ code: '42501' });
  }, 120_000);

  it('records each download of a report’s files in the downloader’s own name, once and for good', async () => {
    const { practice, runId } = await cas03('report downloads');
    const id = await w.requestReport(practice, runId);
    await w.generate(practice, id);
    const record = (actorId: string, by: string, file: string) =>
      inScope(practice, actorId, 'INSERT INTO audit_report_download (practice_id, audit_report_id, file, downloaded_by) VALUES ($1, $2, $3, $4)', [practice.practiceId, id, file, by]);
    await record(practice.manager, practice.manager, 'csv');
    await record(practice.manager, practice.manager, 'pdf');
    const other = await createUser(w.owner);
    await addMembership(w.owner, practice.world.organizationId, other, 'billing_manager');
    await expect(record(practice.manager, other, 'pdf')).rejects.toMatchObject({ code: '42501' });
    await expect(record(practice.manager, practice.manager, 'xlsx')).rejects.toMatchObject({ code: '23514' });
    await expect(inScope(practice, practice.manager, 'INSERT INTO audit_report_download (practice_id, audit_report_id, file, downloaded_by) VALUES ($1, $2, $3, $4)', [practice.practiceId, randomUUID(), 'pdf', practice.manager])).rejects.toMatchObject({ code: '23503' });
    const downloads = await inScope<{ file: string; downloaded_by: string }>(practice, practice.manager, 'SELECT file, downloaded_by FROM audit_report_download WHERE audit_report_id = $1 ORDER BY file', [id]);
    expect(downloads).toEqual([
      { file: 'csv', downloaded_by: practice.manager },
      { file: 'pdf', downloaded_by: practice.manager },
    ]);
    await expect(inScope(practice, practice.manager, "UPDATE audit_report_download SET file = 'pdf'")).rejects.toMatchObject({ code: '42501' });
  }, 120_000);
});
