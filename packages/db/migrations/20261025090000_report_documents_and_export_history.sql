-- ---------------------------------------------------------------------------------------------------
-- The export history
-- ---------------------------------------------------------------------------------------------------

-- The download events of the practice's report files and line-level exports, newest first, a page at a
-- time (at most 200 a page), for a reader of the practice's reports in a scope that reaches it; nothing
-- for anyone else. Definer's rights over the audit log, whose own policy admits the practice's
-- administrators alone; the caller's scope is kept.
CREATE FUNCTION practice_export_history(target uuid, page_size integer, page_offset integer)
RETURNS TABLE (event_id uuid, action text, object_type text, object_id uuid, purpose text, actor_id uuid, at timestamptz)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, public, pg_temp AS $$
  SELECT e.id, e.action, e.object_type, e.object_id, e.purpose, e.actor_id, e.at
    FROM audit_event e
   WHERE practice_in_scope(target) AND coalesce(app_actor_permitted(target, 'report.read'), false)
     AND e.practice_id = target
     AND e.action IN ('audit_report_downloaded', 'roi_statement_downloaded', 'report_document_downloaded', 'monthly_summary_downloaded', 'packet_export_downloaded')
   ORDER BY e.at DESC, e.id DESC
   LIMIT least(greatest(page_size, 0), 200) OFFSET greatest(page_offset, 0)
$$;

CREATE FUNCTION practice_export_count(target uuid) RETURNS integer
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, public, pg_temp AS $$
  SELECT count(*)::integer
    FROM audit_event e
   WHERE practice_in_scope(target) AND coalesce(app_actor_permitted(target, 'report.read'), false)
     AND e.practice_id = target
     AND e.action IN ('audit_report_downloaded', 'roi_statement_downloaded', 'report_document_downloaded', 'monthly_summary_downloaded', 'packet_export_downloaded')
$$;

REVOKE ALL ON FUNCTION report_document_rules(), report_document_belongs(), report_document_no_truncate(), practice_export_history(uuid, integer, integer), practice_export_count(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION practice_export_history(uuid, integer, integer), practice_export_count(uuid) TO tp_app;
