import { createHash, randomUUID } from 'node:crypto';

import { readDatabaseUrl, withPracticeScope } from '@tp/db';
import { addMembership, asOwner, createUser } from '@tp/db/testing';
import { UNPRICED_REASONS } from '@tp/pricing';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';

import { errorOf, type Practice } from '../price/test-support/pricing-world';
import { TriageWorld } from '../triage/test-support/triage-world';
import { COVERAGE_REPORT_FORMAT, type CoverageReportContent, MONTHLY_SUMMARY_FORMAT } from './documents';
import { printReportDocument, reportDocumentHandler } from './print-document';

/**
 * The report document job against PostgreSQL (PRD 5, J12; PRD 6, Reports and exports; docs/adr/0045):
 * a coverage report and a monthly summary generated by a billing manager, in their own name, with
 * SYNTHETIC figures; printed by the job's code (Playwright's Chromium where it is installed), stored
 * sealed with the practice's key and recorded once with the PDF's SHA-256, in no one's name. The
 * database refuses everything else: a document in another person's name or by a viewer, figures in the
 * wrong format, a person recording a PDF, a second print, a change of figures, a deletion.
 */

let w: TriageWorld;

beforeAll(async () => {
  w = await TriageWorld.open(readDatabaseUrl());
}, 60_000);

afterAll(async () => {
  await w.close();
});

const COVERAGE: CoverageReportContent = {
  format: COVERAGE_REPORT_FORMAT,
  generated_on: '2026-10-16',
  run: null,
  lines: { lines: 2, claims: 1, charge_cents: '20000', paid_cents: '10000' },
  priced: { lines: 0, charge_cents: '0' },
  of: { lines: 2, charge_cents: '20000' },
  reasons: UNPRICED_REASONS.map((reason) => ({ reason, lines: 0 })),
  waiting: { lines: 0, claims: 0, charge_cents: '0', paid_cents: '0' },
  waiting_plans: [],
  readiness: { allowed: true, unmapped_plans: 0 },
  pricing_runs: 0,
};

const MONTHLY = {
  format: MONTHLY_SUMMARY_FORMAT,
  generated_on: '2026-10-16',
  month: '2026-03',
  total: {
    payer_id: null,
    payer_name: null,
    figures: Object.fromEntries(
      ['flagged', 'validated', 'actionable', 'payer_approved', 'recovered', 'priced', 'overpaid', 'unpriced', 'not_priced'].map((bucket) => [bucket, { lines: 0, billed_cents: '0', variance_cents: null }]),
    ),
    written_off: { lines: 0, billed_cents: '0', variance_cents: '0' },
  },
  by_payer: [],
};

const sha256 = (bytes: Uint8Array) => createHash('sha256').update(bytes).digest('hex');

async function generate(target: Practice, kind: 'coverage' | 'monthly_summary', content: object, actorId = target.manager, requestedBy = actorId): Promise<string> {
  const id = randomUUID();
  await withPracticeScope(w.app, { actorId, practiceIds: [target.practiceId] }, (scope) =>
    scope.client.query('INSERT INTO report_document (id, practice_id, kind, period, requested_by, content) VALUES ($1, $2, $3, $4, $5, $6)', [
      id,
      target.practiceId,
      kind,
      kind === 'monthly_summary' ? '2026-03' : null,
      requestedBy,
      JSON.stringify(content),
    ]),
  );
  return id;
}

interface DocumentRow {
  status: string;
  pdf_key: string | null;
  pdf_sha256: string | null;
  printed_at: Date | null;
  failure_code: string | null;
}

async function documentRow(target: Practice, id: string): Promise<DocumentRow> {
  const rows = await withPracticeScope(w.app, { actorId: target.manager, practiceIds: [target.practiceId] }, async (scope) =>
    (await scope.client.query<DocumentRow>('SELECT status, pdf_key, pdf_sha256, printed_at, failure_code FROM report_document WHERE id = $1', [id])).rows,
  );
  const [row] = rows;
  if (row === undefined) {
    throw new Error('no such document');
  }
  return row;
}

const services = () => ({ documents: w.reports, keys: w.keys, pdf: w.pdf });

describe('report documents (docs/adr/0045)', () => {
  it('prints a coverage report and a monthly summary once, sealed, with the PDF’s SHA-256, in no one’s name', async () => {
    const practice = await w.practice('documents print');
    for (const [kind, content] of [
      ['coverage', COVERAGE],
      ['monthly_summary', MONTHLY],
    ] as const) {
      const id = await generate(practice, kind, content);
      expect(await documentRow(practice, id)).toMatchObject({ status: 'queued', pdf_key: null, printed_at: null });
      const printed = await printReportDocument(w.pricing.jobContext(practice.practiceId), services(), practice.practiceId, id);
      expect(printed.outcome).toBe('printed');
      const row = await documentRow(practice, id);
      expect(row.status).toBe('ready');
      expect(row.pdf_key).toMatch(new RegExp(`^practices/${practice.practiceId}/reports/${id}/[0-9a-f-]{36}\\.pdf$`));
      expect(row.printed_at).not.toBeNull();
      const stored = await w.stored(practice, row.pdf_key ?? '');
      expect(stored.subarray(0, 5).toString('latin1')).toBe('%PDF-');
      expect(sha256(stored)).toBe(row.pdf_sha256);
      // A replay leaves it as it is (JOB-01).
      expect(await printReportDocument(w.pricing.jobContext(practice.practiceId), services(), practice.practiceId, id)).toEqual({ outcome: 'already_finished', status: 'ready' });
      expect((await documentRow(practice, id)).pdf_sha256).toBe(row.pdf_sha256);
    }
    expect(await printReportDocument(w.pricing.jobContext(practice.practiceId), services(), practice.practiceId, randomUUID())).toEqual({ outcome: 'missing' });
  });

  it('marks a document failed on the print’s third failure, with a fixed code, and logs no figure', async () => {
    const practice = await w.practice('documents failure');
    const id = await generate(practice, 'coverage', COVERAGE);
    const failing = reportDocumentHandler({ ...services(), pdf: { render: () => Promise.reject(new Error('SYNTHETIC printer failure')) } });
    await expect(failing({ practice_id: practice.practiceId, report_document_id: id }, w.pricing.jobContext(practice.practiceId))).rejects.toThrow(/printer/);
    expect((await documentRow(practice, id)).status).toBe('queued');
    await expect(failing({ practice_id: practice.practiceId, report_document_id: id }, w.pricing.jobContext(practice.practiceId, [], true))).rejects.toThrow(/printer/);
    expect(await documentRow(practice, id)).toMatchObject({ status: 'failed', failure_code: 'print_failed', pdf_key: null });
    const logs: Record<string, unknown>[] = [];
    await reportDocumentHandler(services())({ practice_id: practice.practiceId, report_document_id: randomUUID() }, w.pricing.jobContext(practice.practiceId, logs));
    expect(logs.find((line) => line.error_code === 'REPORT_DOCUMENT_NOT_FOUND')).toBeDefined();
  });

  it('refuses a document in another person’s name, by a role that does not work cases, or with figures in another format', async () => {
    const practice = await w.practice('documents refusals');
    const viewer = await createUser(w.owner);
    await addMembership(w.owner, practice.world.organizationId, viewer, 'viewer');
    expect(await errorOf(generate(practice, 'coverage', COVERAGE, viewer))).toMatchObject({ code: '42501' });
    expect(await errorOf(generate(practice, 'coverage', COVERAGE, practice.manager, viewer))).toMatchObject({ code: '42501' });
    expect(await errorOf(generate(practice, 'coverage', MONTHLY))).toMatchObject({ code: '23514' });
    expect(await errorOf(generate(practice, 'monthly_summary', COVERAGE))).toMatchObject({ code: '23514' });
  });

  it('lets no person record a PDF, and no one change its figures, print it twice or delete it', async () => {
    const practice = await w.practice('documents rules');
    const id = await generate(practice, 'coverage', COVERAGE);
    const asManager = (sql: string, values: unknown[]) => withPracticeScope(w.app, { actorId: practice.manager, practiceIds: [practice.practiceId] }, (scope) => scope.client.query(sql, values));
    const key = `practices/${practice.practiceId}/reports/${id}/${randomUUID()}.pdf`;
    expect(await errorOf(asManager("UPDATE report_document SET status = 'ready', pdf_key = $2, pdf_sha256 = $3 WHERE id = $1", [id, key, 'a'.repeat(64)]))).toMatchObject({ code: '42501' });
    await printReportDocument(w.pricing.jobContext(practice.practiceId), services(), practice.practiceId, id);
    const job = w.pricing.jobContext(practice.practiceId);
    expect(await errorOf(job.transaction((scope) => scope.client.query("UPDATE report_document SET status = 'failed', failure_code = 'print_failed', pdf_key = NULL, pdf_sha256 = NULL WHERE id = $1", [id])))).toMatchObject({ code: '23514' });
    expect(await errorOf(asOwner(w.owner, [practice.practiceId], () => w.owner.query("UPDATE report_document SET content = '{\"format\":\"tp-coverage-report/1\",\"altered\":true}' WHERE id = $1", [id])))).toMatchObject({ code: '23514' });
    expect(await errorOf(asOwner(w.owner, [practice.practiceId], () => w.owner.query('DELETE FROM report_document WHERE id = $1', [id])))).toMatchObject({ code: '23514' });
    expect(await errorOf(asManager('DELETE FROM report_document WHERE id = $1', [id]))).toMatchObject({ code: '42501' });
    // A PDF under another document's key is refused, even for the job.
    const other = await generate(practice, 'coverage', COVERAGE);
    expect(
      await errorOf(job.transaction((scope) => scope.client.query("UPDATE report_document SET status = 'ready', pdf_key = $2, pdf_sha256 = $3 WHERE id = $1", [other, key, 'b'.repeat(64)]))),
    ).toMatchObject({ code: '23514' });
  });
});
