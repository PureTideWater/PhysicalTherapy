#!/usr/bin/env bash
# PreToolUse on Edit|Write|MultiEdit|NotebookEdit. Refuses any X12 content under fixtures/ or packages/synth/ whose
# ISA06 sender is not SYNTHSENDER, and any file anywhere that looks like a real remittance (a Write's content, an
# Edit's or a MultiEdit's new strings, a NotebookEdit's new source). Under fixtures/ or packages/synth/ it also
# refuses any write of a spreadsheet (.xlsx, .xls, .xlsm, .ods and the like) and any NotebookEdit (no notebook is a
# fixture, and the guard cannot rebuild what one leaves; docs/adr/0063), and checks the file a Write, Edit or
# MultiEdit would leave (a CSV or TSV above all) with the writer's own guard, packages/synth/src/guard/cli.ts:
# SYNTHSENDER in an identifier column of every data row (docs/adr/0059). Fails closed without jq, node or tsx.
set -u
command -v jq >/dev/null 2>&1 || { echo "fixture-guard: jq is required" >&2; exit 2; }
input=$(cat)
file_path=$(printf '%s' "$input" | jq -r '.tool_input.file_path // .tool_input.notebook_path // empty') || { echo "fixture-guard: the hook input is not JSON" >&2; exit 2; }
content=$(printf '%s' "$input" | jq -r '.tool_input.content // .tool_input.new_string // .tool_input.new_source // empty')
if [ -n "$content" ]; then
  case "$content" in
    ISA*)
      sender=$(printf '%s' "$content" | cut -c36-50 | tr -d ' ')
      if [ "$sender" != "SYNTHSENDER" ]; then
        echo "Blocked: $file_path contains an X12 interchange whose sender is not SYNTHSENDER. Real remittances never enter the repository. Generate a twin with pnpm synth." >&2
        exit 2
      fi ;;
  esac
fi
# The same rule for each edit of a MultiEdit, whose new strings the line above does not read.
edit_senders=$(printf '%s' "$input" | jq -r '.tool_input.edits[]? | (.new_string // "") | strings | select(startswith("ISA")) | .[35:50] | gsub(" "; "")') || { echo "fixture-guard: the hook input is not JSON" >&2; exit 2; }
while IFS= read -r sender; do
  if [ -n "$sender" ] && [ "$sender" != "SYNTHSENDER" ]; then
    echo "Blocked: $file_path contains an X12 interchange whose sender is not SYNTHSENDER. Real remittances never enter the repository. Generate a twin with pnpm synth." >&2
    exit 2
  fi
done <<< "$edit_senders"

# The file's path in its own repository (a worktree is its own): "." and ".." segments taken out, symbolic links
# resolved (the file itself, as a Write follows it, and the part of its directory that exists), and compared in any
# case, so no spelling of a fixture's path slips past.
[ -n "$file_path" ] || exit 0
cwd=$(printf '%s' "$input" | jq -r '.cwd // empty')
root=$(cd "${cwd:-.}" 2>/dev/null && git rev-parse --show-toplevel 2>/dev/null) || root="${cwd:-$PWD}"
case "$file_path" in /*) abs="$file_path" ;; *) abs="$root/$file_path" ;; esac
clean_path() {
  local parts=() clean=() part
  IFS=/ read -r -a parts <<< "$1"
  for part in ${parts[@]+"${parts[@]}"}; do
    case "$part" in
      ''|.) ;;
      ..) [ "${#clean[@]}" -eq 0 ] || unset 'clean[${#clean[@]}-1]' ;;
      *) clean+=("$part") ;;
    esac
  done
  printf '/%s' ${clean[@]+"${clean[@]}"}
}
abs=$(clean_path "$abs")
hops=0
while :; do
  dir=$(dirname "$abs")
  while [ ! -d "$dir" ]; do dir=$(dirname "$dir"); done
  real=$(cd "$dir" 2>/dev/null && pwd -P) || real="$dir"
  tail=${abs#"$dir"}
  abs="${real%/}/${tail#/}"
  [ -L "$abs" ] && [ "$hops" -lt 40 ] || break
  target=$(readlink "$abs") || { echo "fixture-guard: could not read the link $file_path, so it is refused" >&2; exit 2; }
  case "$target" in /*) ;; *) target="$(dirname "$abs")/$target" ;; esac
  abs=$(clean_path "$target")
  hops=$((hops + 1))
done
real=$(dirname "$abs")
while [ ! -d "$real" ]; do real=$(dirname "$real"); done
own=$(cd "$real" 2>/dev/null && git rev-parse --show-toplevel 2>/dev/null) || own="$root"
rel=${abs#"$own"/}
lower=$(printf '%s' "$rel" | tr '[:upper:]' '[:lower:]')
case "$lower" in fixtures/*|packages/synth/*) ;; *) exit 0 ;; esac
if [ "$(printf '%s' "$input" | jq -r '.tool_name // empty')" = "NotebookEdit" ]; then
  echo "Blocked: $file_path is under fixtures/ or packages/synth/, where no notebook belongs, and the fixture guard cannot rebuild what a NotebookEdit leaves. Generate fixtures with pnpm synth." >&2
  exit 2
fi
case "$lower" in
  *.xlsx|*.xls|*.xlsm|*.xlsb|*.xltx|*.xltm|*.ods|*.fods|*.numbers)
    echo "Blocked: $file_path is a spreadsheet under fixtures/ or packages/synth/. A workbook fixture is generated by packages/synth, which checks it for SYNTHSENDER; it is never written by hand." >&2
    exit 2 ;;
  # Source, data and documents: no fixture rule reads them, and the hook stays fast for them.
  *.ts|*.tsx|*.js|*.mjs|*.cjs|*.json|*.md) exit 0 ;;
esac

# Anything else there (a CSV or TSV, an .835, a text file) is checked as the file the call would leave.
here=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
tsx="$here/node_modules/.bin/tsx"
command -v node >/dev/null 2>&1 || { echo "fixture-guard: node is required to check $file_path" >&2; exit 2; }
[ -x "$tsx" ] || { echo "fixture-guard: tsx is required to check $file_path (pnpm install)" >&2; exit 2; }
printf '%s' "$input" | "$tsx" "$here/packages/synth/src/guard/cli.ts" --hook --label "$rel" --file "$abs" && exit 0
exit 2
